// 统一 SVG 图标库：所有 UI 图标在此集中管理（不使用 emoji/Unicode 符号）
// 约定：均使用 currentColor，尺寸由调用方通过 size/className 控制

interface IconProps {
  size?: number;
  className?: string;
  style?: React.CSSProperties;
}

function Svg({
  size = 16,
  className,
  style,
  children,
  viewBox = "0 0 24 24",
}: IconProps & { children: React.ReactNode; viewBox?: string }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox={viewBox}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={{ flexShrink: 0, ...style }}
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

